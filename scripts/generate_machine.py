#!/usr/bin/env python3
"""Generate an audited GG-only binding for every upstream system port."""
import json,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def main():
    source=(ROOT/'rtl/generated/system.vhdl').read_text()
    clean=re.sub(r'--[^\n]*','',source)
    port=re.search(r'entity system is.*?port\s*\((.*?)\);\s*end system;',clean,re.S|re.I).group(1)
    explicit={
      'clk_sys':'clk','ce_cpu':'ce_cpu and not freeze','ce_vdp':'ce_vdp and not freeze',
      'ce_pix':'ce_pix and not freeze','ce_sp':'ce_sp and not freeze',
      'reset_n':'effective_reset_n','rom_wait_n':'rom_wait_n','gg':'not machine_sms',
      'ggres':'not machine_sms','dbr':"'1'",
      'romen':'load_we','romcl':'clk','romad':"'0' & load_address",'romdt':'load_data',
      'rom_rd':'rom_read','rom_a':'rom_address','rom_do':'rom_data',
      'j1_up':'not buttons(0)','j1_down':'not buttons(1)','j1_left':'not buttons(2)',
      'j1_right':'not buttons(3)','j1_tl':'not buttons(4)','j1_tr':'not buttons(5)',
      'pause':'not buttons(6)', 'region':'region',
      'pal':'tv_pal',
      'j1_th':"'1'", 'j2_up':"'1'",'j2_down':"'1'",'j2_left':"'1'",'j2_right':"'1'",
      'j2_tl':"'1'",'j2_tr':"'1'",'j2_th':"'1'",'gg_link_in':"(others => '1')",
      'mapper_lock':'force_sega','mapper_codies_force':'force_codies',
      'mapper_dahjee_a_force':'force_dahjee','mapper_linear_force':'force_linear','mapper_zemina_force':'force_zemina',
      'x':'x','y':'y','vcounter_cpu':'vcounter','color':'color','smode_m1':'m1','smode_m2':'m2','smode_m3':'m3','smode_m4':'m4',
      'audiol':'audio_left','audior':'audio_right','audio_phase_in':"'0'",'audio_phase_set':'not effective_reset_n',
      'ram_a':'wram_a','ram_d':'wram_d','ram_we':'wram_we','ram_q':'wram_q',
      'nvram_a':'save_a','nvram_d':'save_d','nvram_we':'save_we','nvram_q':'save_q',
      'ss_freeze':'freeze','z80_reg_out':'debug_cpu','vdp_regs_out':'debug_vdp',
      'vdp_cram_out':'debug_cram','io_state_out':'debug_io','mapper_out':'debug_mapper',
    }
    ledger=[]; bindings=[]
    for declaration in port.split(';'):
        declaration=declaration.strip()
        if not declaration:continue
        match=re.fullmatch(r'([\w\s,]+)\s*:\s*(in|out)\s+(.+)',declaration,re.I|re.S)
        if not match:raise ValueError(declaration)
        names,direction,typ=match.groups()
        for name in re.sub(r'\s+','',names).split(','):
            key=name.lower()
            value=explicit.get(key)
            if value is None:value='open' if direction.lower()=='out' else "(others => '0')" if 'vector' in typ.lower() else "'0'"
            bindings.append(f'      {name} => {value}')
            ledger.append({'port':name,'direction':direction.lower(),'type':typ.strip(),'binding':value,'explicit':key in explicit})
    template='''-- SPDX-License-Identifier: GPL-3.0-or-later
-- Generated by scripts/generate_machine.py; input bindings are in manifests/bindings.json.
library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;
entity gamegear_machine is
  port(clk,reset_n,clear_wram,freeze:in std_logic;
       machine_sms,tv_pal:in std_logic;
       ce_cpu,ce_vdp,ce_pix,ce_sp,rom_wait_n:in std_logic;
       buttons:in std_logic_vector(6 downto 0); region:in std_logic;
       mapper:in std_logic_vector(3 downto 0);
       load_we:in std_logic; load_address:in std_logic_vector(23 downto 0); load_data:in std_logic_vector(7 downto 0);
       rom_read:out std_logic; rom_address:out std_logic_vector(23 downto 0); rom_data:in std_logic_vector(7 downto 0);
       color:out std_logic_vector(11 downto 0); hblank,vblank:out std_logic;
       audio_left,audio_right:out std_logic_vector(15 downto 0);
       save_host_address:in std_logic_vector(14 downto 0); save_host_data:in std_logic_vector(7 downto 0);
       save_host_we:in std_logic; save_host_q:out std_logic_vector(7 downto 0);
       debug_wram_address:in std_logic_vector(12 downto 0); debug_wram_q:out std_logic_vector(7 downto 0);
       wram_busy:out std_logic;
       debug_cpu:out std_logic_vector(229 downto 0); debug_vdp:out std_logic_vector(127 downto 0);
       debug_cram:out std_logic_vector(383 downto 0); debug_io:out std_logic_vector(31 downto 0);
       debug_mapper:out std_logic_vector(63 downto 0));
end;
architecture rtl of gamegear_machine is
  signal x,y:std_logic_vector(8 downto 0);
  signal vcounter:std_logic_vector(7 downto 0);
  signal m1,m2,m3,m4:std_logic;
  signal wram_a:std_logic_vector(13 downto 0);
  signal wram_d,wram_q:std_logic_vector(7 downto 0);
  signal wram_we:std_logic;
  signal save_a:std_logic_vector(14 downto 0);
  signal save_d,save_q:std_logic_vector(7 downto 0);
  signal save_we:std_logic;
  signal save_mem_a:std_logic_vector(14 downto 0);
  signal save_mem_d:std_logic_vector(7 downto 0);
  signal save_mem_we:std_logic;
  signal force_sega,force_codies,force_dahjee,force_linear,force_zemina:std_logic;
  signal effective_reset_n,clearing:std_logic:='0';
  signal clear_addr:unsigned(12 downto 0):=(others=>'0');
  signal ram_addr:std_logic_vector(12 downto 0);
  signal ram_data:std_logic_vector(7 downto 0);
  signal ram_write:std_logic;
begin
  wram_busy<=clearing;
  effective_reset_n<=reset_n and not clearing;
  force_sega<='1' when mapper=x"1" else '0';
  force_codies<='1' when mapper=x"2" else '0';
  force_dahjee<='1' when mapper=x"3" else '0';
  force_linear<='1' when mapper=x"4" else '0';
  force_zemina<='1' when mapper=x"5" else '0';
  process(clk) begin
    if rising_edge(clk) then
      if clear_wram='1' then clearing<='1'; clear_addr<=(others=>'0');
      elsif clearing='1' then
        if clear_addr=8191 then clearing<='0'; else clear_addr<=clear_addr+1; end if;
      end if;
    end if;
  end process;
  ram_addr<=std_logic_vector(clear_addr) when clearing='1' else wram_a(12 downto 0);
  ram_data<=(others=>'0') when clearing='1' else wram_d;
  ram_write<=clearing or (wram_we and not freeze);
  work_ram:entity work.dpram generic map(widthad_a=>13)
    port map(clock_a=>clk,clock_b=>clk,address_a=>ram_addr,address_b=>debug_wram_address,
      data_a=>ram_data,data_b=>(others=>'0'),wren_a=>ram_write,wren_b=>'0',q_a=>wram_q,q_b=>debug_wram_q);
  -- Save import writes port A while the engine is frozen; port B stays read-only.
  save_mem_a<=save_host_address when save_host_we='1' else save_a;
  save_mem_d<=save_host_data when save_host_we='1' else save_d;
  save_mem_we<=save_host_we or (save_we and not freeze);
  save_ram:entity work.dpram generic map(widthad_a=>15,init_file=>"ff")
    port map(clock_a=>clk,clock_b=>clk,address_a=>save_mem_a,address_b=>save_host_address,
      data_a=>save_mem_d,data_b=>(others=>'0'),wren_a=>save_mem_we,wren_b=>'0',q_a=>save_q,q_b=>save_host_q);
  raster:entity work.video port map(clk=>clk,ce_pix=>ce_pix and not freeze,pal=>tv_pal,border=>'0',
    ggres=>not machine_sms,mask_column=>'0',cut_mask=>'0',smode_M1=>m1,smode_M2=>m2,smode_M3=>m3,smode_M4=>m4,
    video_state_out=>open,x=>x,y=>y,vcounter_cpu=>vcounter,hsync=>open,vsync=>open,hblank=>hblank,vblank=>vblank);
  sega:entity work.system generic map(MAX_SPPL=>7)
    port map(
BINDINGS
    );
end;
'''
    output=ROOT/'rtl/platform/gamegear_machine.vhdl';output.parent.mkdir(parents=True,exist_ok=True)
    output.write_text(template.replace('BINDINGS',',\n'.join(bindings)))
    (ROOT/'manifests/bindings.json').write_text(json.dumps(ledger,indent=2)+'\n')
    print(f'Generated {len(ledger)} audited system port bindings')
if __name__=='__main__':main()
